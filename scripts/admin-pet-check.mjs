import assert from 'node:assert/strict';
import { browser, delay } from './browser.mjs';

const b = await browser();
try {
  const page = await b.page('admin-pet', 1120, 820);
  await page.nav(`${process.env.BASE || 'http://127.0.0.1:8787'}/?debug=1`);
  await page.wait('window.__ftw?.world');
  await page.eval(`import('./js/profile.js').then(({profile,replaceProfile}) => replaceProfile({...profile,petTiers:{piggy:{1:1}},pets:{piggy:1},discoveredPets:['piggy']}))`);
  await page.clickText('Create Private');
  await page.wait('window.__ftw.state.inRoom');
  assert.deepEqual(await page.eval('[...document.querySelectorAll(".side .side-btn")].map(e=>e.getAttribute("aria-label"))'), ['Invite','Shop','Pets','Cards','Trade','Free','Profile','Settings']);
  assert.equal(await page.eval('document.querySelector(".counters > .side-btn")?.getAttribute("aria-label")'), 'Game Settings');
  await page.eval('document.activeElement?.blur()');
  await page.key('p', 'KeyP', 80, 'p');
  assert.equal(await page.eval('window.__ftw.profile.settings.view'), 'first');
  assert.ok((await page.eval('document.querySelector(".toast")?.textContent || ""')).includes('Press P'));
  await page.key('p', 'KeyP', 80, 'p');
  await page.click('[aria-label="Profile"]');
  await page.clickText('Pets', '.profile-tabs button');
  await page.cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 5, y: 5 });
  await delay(120);
  const rect = await page.eval(`(() => { const r=document.querySelector('.profile-item').getBoundingClientRect(); return {x:r.left+r.width/2,y:r.top+r.height/2}; })()`);
  await page.cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: rect.x, y: rect.y });
  await delay(1000);
  assert.equal(await page.eval('!!document.querySelector(".pet-stat-tooltip")'), false);
  await delay(1150);
  assert.ok((await page.eval('document.querySelector(".pet-stat-tooltip")?.textContent || ""')).includes('−1 sec'));
  await page.shot('pet-tooltip');
  await page.click('[aria-label="Settings"]');
  assert.equal(await page.eval('document.querySelector(".panel-settings .secret-entry").hidden'), true);
  assert.equal(await page.eval('document.querySelector(".panel-settings .btn.purple")?.hidden'), true);
  for (let i = 0; i < 5; i++) await page.click('.panel-settings .version-entry');
  assert.equal(await page.eval('document.querySelector(".panel-settings .secret-entry").hidden'), false);
  await page.key('Escape', 'Escape', 27);
  await page.eval(`window.__ftw.state.isAdmin=true; window.__ftw.state.adminRooms=[{code:'PRIVT',public:false,humans:1,players:[{id:'otherplayer',name:'Other Player'}]}]; window.__ftw.state.adminLeaders=[{id:'leader1',name:'Leader',wins:12}]; window.__ftw.actions.refreshPanels()`);
  await page.clickText('Open admin tools', '.panel-settings button');
  assert.ok(await page.eval(`document.querySelector('.admin-room-list')?.textContent.includes('PRIVT · Private')`));
  await page.clickText('Other Player', '.admin-room-players button');
  assert.equal(await page.eval(`document.querySelector('[aria-label="Player ID for wins"]').value`), 'otherplayer');
  await page.clickText('Leader · 12', '.admin-room-players button');
  assert.equal(await page.eval(`document.querySelector('[aria-label="Player ID for wins"]').value`), 'leader1');
  await page.eval(`document.querySelector('.panel-settings .panel-body').scrollTop=10000`);
  await page.shot('admin-rooms');
  await page.click('[aria-label="Pets"]');
  assert.equal(await page.eval('document.querySelectorAll(".pet-dictionary-card").length'), 12);
  assert.equal(await page.eval('document.querySelectorAll(".pet-dictionary-card button").length'), 12);
  assert.ok((await page.eval('document.querySelector(".pet-dictionary")?.textContent || ""')).includes('Not discovered'));
  await page.shot('pet-dictionary');
  assert.deepEqual(page.errors, []);
  console.log('PASS delayed pet stats, pet dictionary and admin room/player controls');
} finally { await b.close(); }
